function buildZoneSlots(
  zoneId: string,
  prefix: string,
  specs: { count: number; vehicleType: VehicleType; allowedRoles: UserRole[] }[]
): ParkingSlot[] {
  const slots: ParkingSlot[] = [];
  let counter = 1;
  const totalCount = specs.reduce((acc, s) => acc + s.count, 0);
  const half = Math.ceil(totalCount / 2);

  for (const spec of specs) {
    for (let i = 0; i < spec.count; i++) {
      const id = `${prefix}-${String(counter).padStart(2, '0')}`;
      const override = SLOT_OVERRIDES[id];
      const row: 'A' | 'B' = counter <= half ? 'A' : 'B';
      const indexInRow = row === 'A' ? counter : counter - half;

      slots.push({
        id,
        zoneId,
        row,
        indexInRow,
        vehicleType: spec.vehicleType,
        allowedRoles: spec.allowedRoles,
        status: override?.status ?? 'available',
        vehicleReg: override?.vehicleReg,
        vehicleModel: override?.vehicleModel,
        occupantName: override?.occupantName,
        occupantRole: override?.occupantRole,
        occupantId: override?.occupantId,
        department: override?.department,
        since: override?.since,
        reservedUntil: override?.reservedUntil,
        notes: override?.notes,
      });
      counter++;
    }
  }
  return slots;
}

